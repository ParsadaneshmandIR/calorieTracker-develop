CREATE TABLE food (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255)  NOT NULL,
    name_fa             VARCHAR(255)  NOT NULL,
    kcal_per_100g       DECIMAL(12, 4) NOT NULL,
    protein_per_100g    DECIMAL(12, 4) NOT NULL,
    carb_per_100g       DECIMAL(12, 4) NOT NULL,
    fat_per_100g        DECIMAL(12, 4) NOT NULL,
    fiber_per_100g      DECIMAL(12, 4),
    state               VARCHAR(32)   NOT NULL,
    edible_portion_pct  DECIMAL(8, 4) NOT NULL DEFAULT 100,
    source              VARCHAR(32)   NOT NULL,
    source_id           VARCHAR(128)  NOT NULL,
    license             VARCHAR(128),
    fetched_at          TIMESTAMP WITH TIME ZONE,
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_food_source_source_id UNIQUE (source, source_id),
    CONSTRAINT chk_food_state CHECK (state IN ('RAW', 'COOKED', 'PACKAGED')),
    CONSTRAINT chk_food_source CHECK (source IN ('USDA', 'OPEN_FOOD_FACTS', 'MANUAL')),
    CONSTRAINT chk_food_kcal_nonneg CHECK (kcal_per_100g >= 0),
    CONSTRAINT chk_food_edible_pct CHECK (edible_portion_pct > 0 AND edible_portion_pct <= 100)
);

CREATE INDEX idx_food_name ON food (name);
CREATE INDEX idx_food_name_fa ON food (name_fa);
CREATE INDEX idx_food_state ON food (state);

CREATE TABLE portion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_id    BIGINT         NOT NULL,
    label      VARCHAR(128)   NOT NULL,
    label_fa   VARCHAR(128)   NOT NULL,
    grams      DECIMAL(12, 4) NOT NULL,
    CONSTRAINT fk_portion_food FOREIGN KEY (food_id) REFERENCES food (id) ON DELETE CASCADE,
    CONSTRAINT chk_portion_grams_positive CHECK (grams > 0)
);

CREATE INDEX idx_portion_food_id ON portion (food_id);

CREATE TABLE meal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    eaten_date  DATE         NOT NULL,
    eaten_time  TIME         NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_meal_eaten_date ON meal (eaten_date);

CREATE TABLE meal_entry (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id           BIGINT         NOT NULL,
    food_id           BIGINT         NOT NULL,
    grams             DECIMAL(12, 4) NOT NULL,
    portion_id        BIGINT,
    computed_kcal     DECIMAL(12, 4) NOT NULL,
    computed_protein  DECIMAL(12, 4) NOT NULL,
    computed_carb     DECIMAL(12, 4) NOT NULL,
    computed_fat      DECIMAL(12, 4) NOT NULL,
    CONSTRAINT fk_meal_entry_meal FOREIGN KEY (meal_id) REFERENCES meal (id) ON DELETE CASCADE,
    CONSTRAINT fk_meal_entry_food FOREIGN KEY (food_id) REFERENCES food (id),
    CONSTRAINT fk_meal_entry_portion FOREIGN KEY (portion_id) REFERENCES portion (id),
    CONSTRAINT chk_meal_entry_grams_positive CHECK (grams > 0)
);

CREATE INDEX idx_meal_entry_meal_id ON meal_entry (meal_id);

CREATE TABLE recipe (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255)  NOT NULL,
    name_fa             VARCHAR(255)  NOT NULL,
    total_weight_grams  DECIMAL(12, 4) NOT NULL,
    servings            INT           NOT NULL,
    instructions        TEXT,
    CONSTRAINT chk_recipe_weight_positive CHECK (total_weight_grams > 0),
    CONSTRAINT chk_recipe_servings_positive CHECK (servings > 0)
);

CREATE TABLE recipe_ingredient (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT         NOT NULL,
    food_id    BIGINT         NOT NULL,
    grams      DECIMAL(12, 4) NOT NULL,
    CONSTRAINT fk_recipe_ingredient_recipe FOREIGN KEY (recipe_id) REFERENCES recipe (id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredient_food FOREIGN KEY (food_id) REFERENCES food (id),
    CONSTRAINT chk_recipe_ingredient_grams_positive CHECK (grams > 0)
);

CREATE INDEX idx_recipe_ingredient_recipe_id ON recipe_ingredient (recipe_id);
